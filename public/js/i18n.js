window.I18N = {
  lang: localStorage.getItem('lang') || (navigator.language || 'ru').slice(0, 2),
  init() {
    if (!window.DICT[this.lang]) this.lang = 'ru';
    document.documentElement.lang = this.lang;
  },
  set(code) {
    if (!window.DICT[code]) return;
    this.lang = code;
    localStorage.setItem('lang', code);
    document.documentElement.lang = code;
  },
  t(key) {
    const d = window.DICT[this.lang] || window.DICT.ru;
    return d[key] !== undefined ? d[key] : (window.DICT.ru[key] !== undefined ? window.DICT.ru[key] : key);
  },
};
window.t = (k) => window.I18N.t(k);
