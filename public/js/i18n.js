window.I18N = {
  lang: localStorage.getItem('lang') || (navigator.language || 'ru').slice(0, 2),
  init() {
    if (!window.DICT[this.lang]) this.lang = 'ru';
    document.documentElement.lang = this.lang;
    document.title = this.t('metaTitle');
  },
  set(code) {
    if (!window.DICT[code]) return;
    this.lang = code;
    localStorage.setItem('lang', code);
    document.documentElement.lang = code;
  },
  t(key, vars) {
    const d = window.DICT[this.lang] || window.DICT.ru;
    let s = d[key] !== undefined ? d[key] : (window.DICT.ru[key] !== undefined ? window.DICT.ru[key] : key);
    if (vars && typeof vars === 'object') {
      for (const [name, val] of Object.entries(vars)) {
        s = String(s).split('%' + name + '%').join(String(val));
      }
    }
    return s;
  },
};
window.t = (k, vars) => window.I18N.t(k, vars);
